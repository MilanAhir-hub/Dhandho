from typing import Optional, Dict, Any, List
from fastapi import APIRouter, Depends, HTTPException, status
from pydantic import BaseModel
from sqlalchemy.orm import Session
from langchain_core.messages import AIMessage

# Import database session dependency
from database import get_db

# Import AI assistant runner and checkpointer
from ai.agent import ask_ai_assistant, build_ai_graph
from ai.proposals import execute_proposal, reject_proposal, get_proposal

# Step 1: Create API router for AI endpoints
router = APIRouter(prefix="/ai", tags=["AI Assistant"])

# Step 2: Define request schema for incoming user chat message
class ChatRequest(BaseModel):
    # Message sent by shopkeeper
    message: str
    # Unique conversation ID for stateful session tracking
    conversation_id: Optional[str] = "default_conversation"
    # ID of the authenticated user to isolate conversation memory
    user_id: Optional[int] = 1

# Step 3: Define response schema including response text, active state, and pending proposals
class ChatResponse(BaseModel):
    # Friendly response generated by AI agent
    response: str
    # Current active intent (e.g. "add_product", "pending_approval", or None)
    intent: Optional[str] = None
    # Information collected so far
    collected_data: Optional[Dict[str, Any]] = None
    # Remaining missing fields
    missing_fields: Optional[List[str]] = None
    # Pending proposal waiting for human review
    proposal: Optional[Dict[str, Any]] = None

# Step 4: Define request schema for proposal actions (Approve / Reject)
class ProposalActionRequest(BaseModel):
    # The unique UUID of the proposal
    proposal_id: str
    # The conversation ID this proposal belongs to
    conversation_id: Optional[str] = "default_conversation"
    # Authenticated user ID
    user_id: Optional[int] = 1

# Step 5: Define response schema for proposal actions
class ProposalActionResponse(BaseModel):
    # Status of the action ("executed", "rejected", "already_rejected")
    status: str
    # The proposal ID
    proposal_id: str
    # User-friendly explanation message
    message: str
    # Generated database ID if a product was created
    product_id: Optional[int] = None
    # Product name if executed
    product_name: Optional[str] = None

# Step 6: POST /ai/chat endpoint to interact with LangGraph agent
@router.post("/chat", response_model=ChatResponse)
def chat_with_assistant(data: ChatRequest, db: Session = Depends(get_db)):
    # Validate non-empty message
    if not data.message or not data.message.strip():
        raise HTTPException(status_code=400, detail="Message cannot be empty.")
        
    try:
        # Run user query through LangGraph workflow with thread memory
        result = ask_ai_assistant(
            user_message=data.message.strip(),
            db=db,
            conversation_id=data.conversation_id or "default_conversation",
            user_id=data.user_id or 1,
        )
        # Return structured response
        return ChatResponse(
            response=result["response"],
            intent=result.get("intent"),
            collected_data=result.get("collected_data"),
            missing_fields=result.get("missing_fields"),
            proposal=result.get("proposal"),
        )
    except Exception as e:
        # Return informative error if anything fails
        raise HTTPException(status_code=500, detail=f"AI Agent error: {str(e)}")

# Step 7: POST /ai/proposal/approve endpoint to authorize and execute database change
@router.post("/proposal/approve", response_model=ProposalActionResponse)
@router.post("/chat/approve", response_model=ProposalActionResponse)
def approve_change(data: ProposalActionRequest, db: Session = Depends(get_db)):
    # Check proposal existence
    proposal = get_proposal(data.proposal_id)
    if not proposal:
        raise HTTPException(status_code=404, detail="Proposal not found.")

    try:
        # Execute the database write through existing backend CRUD
        result = execute_proposal(
            proposal_id=data.proposal_id,
            user_id=data.user_id or 1,
            db=db,
        )
        
        # Update LangGraph conversation memory with confirmation message
        thread_id = f"user_{data.user_id or 1}_conv_{data.conversation_id or 'default_conversation'}"
        graph = build_ai_graph(db)
        confirmation_msg = f"✓ Approved! {result['message']}"
        graph.update_state(
            {"configurable": {"thread_id": thread_id}},
            {"messages": [AIMessage(content=confirmation_msg)], "intent": None, "pending_proposal": None},
        )
        
        # Return structured execution result
        return ProposalActionResponse(**result)
    except PermissionError as pe:
        # Unauthorized access error
        raise HTTPException(status_code=status.HTTP_403_FORBIDDEN, detail=str(pe))
    except ValueError as ve:
        # Validation or replay error
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail=str(ve))
    except Exception as e:
        # General failure
        raise HTTPException(status_code=500, detail=f"Execution error: {str(e)}")

# Step 8: POST /ai/proposal/reject endpoint to reject and discard proposed change
@router.post("/proposal/reject", response_model=ProposalActionResponse)
@router.post("/chat/reject", response_model=ProposalActionResponse)
def reject_change(data: ProposalActionRequest, db: Session = Depends(get_db)):
    # Check proposal existence
    proposal = get_proposal(data.proposal_id)
    if not proposal:
        raise HTTPException(status_code=404, detail="Proposal not found.")

    try:
        # Mark proposal rejected on server without modifying database
        result = reject_proposal(
            proposal_id=data.proposal_id,
            user_id=data.user_id or 1,
        )
        
        # Update LangGraph conversation memory with cancellation message
        thread_id = f"user_{data.user_id or 1}_conv_{data.conversation_id or 'default_conversation'}"
        graph = build_ai_graph(db)
        cancel_msg = f"✗ Rejected: {result['message']}"
        graph.update_state(
            {"configurable": {"thread_id": thread_id}},
            {"messages": [AIMessage(content=cancel_msg)], "intent": None, "pending_proposal": None},
        )
        
        # Return structured rejection result
        return ProposalActionResponse(**result)
    except PermissionError as pe:
        # Unauthorized access error
        raise HTTPException(status_code=status.HTTP_403_FORBIDDEN, detail=str(pe))
    except ValueError as ve:
        # Validation error
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail=str(ve))
    except Exception as e:
        # General failure
        raise HTTPException(status_code=500, detail=f"Rejection error: {str(e)}")
